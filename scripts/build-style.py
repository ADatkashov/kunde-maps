def zoom(*stops):
    """interpolate-by-zoom helper: zoom(5, 0.3, 11, 1.6)."""
    expr = ["interpolate", ["exponential", 1.4], ["zoom"]]
    for z, value in zip(stops[::2], stops[1::2]):
        expr += [z, value]
    return expr


def name_field(lang="ru"):
    """text-field for a localised label; regenerated by the web app when the UI language changes."""
    if lang == "kk":
        return ["coalesce", ["get", "name:kk"], ["get", "name"], ["get", "name:ru"], ["get", "name:latin"], ""]
    if lang == "en":
        return ["coalesce", ["get", "name:en"], ["get", "name:latin"], ["get", "name"], ""]
    return ["coalesce", ["get", "name:ru"], ["get", "name"], ["get", "name:kk"], ["get", "name:latin"], ""]


def build(theme):
    c = PALETTES[theme]
    layers = []

    def add(layer, text=None):
        """text: callable(lang) -> text-field expression. All languages are stored in layer metadata ("kunde:text") so the
        web app can switch language with setStyle without knowing each layer's template."""
        if text:
            layer["layout"]["text-field"] = text("ru")
            layer.setdefault("metadata", {})["kunde:text"] = {lang: text(lang) for lang in ("ru", "kk", "en")}
        layers.append(layer)

    add({"id": "background", "type": "background", "paint": {"background-color": c["background"]}})

    # Land cover / land use (broad, quiet colours; nothing competes with roads and labels)
    add({"id": "landcover", "type": "fill", "source": SRC, "source-layer": "landcover", "paint": {
        "fill-color": ["match", ["get", "class"], "wood", c["wood"], "grass", c["grass"], "farmland", c["farmland"],
                       "wetland", c["wetland"], "sand", c["sand"], "rock", c["rock"], "ice", c["ice"], c["grass"]],
        "fill-opacity": zoom(2, 0.55, 10, 0.8, 14, 0.9)}})
    add({"id": "landuse", "type": "fill", "source": SRC, "source-layer": "landuse", "minzoom": 8, "paint": {
        "fill-color": ["match", ["get", "class"], "residential", c["residential"], "commercial", c["commercial"],
                       "industrial", c["industrial"], "retail", c["retail"], "cemetery", c["cemetery"],
                       ["school", "hospital", "university", "college", "kindergarten"], c["institution"],
                       ["pitch", "playground", "stadium", "track"], c["grass"], "railway", c["industrial"], "quarry", c["rock"], c["residential"]],
        "fill-opacity": zoom(8, 0.0, 11, 0.7, 14, 0.95)}})
    add({"id": "park", "type": "fill", "source": SRC, "source-layer": "park", "minzoom": 5, "paint": {
        "fill-color": c["park"], "fill-opacity": zoom(5, 0.25, 10, 0.55, 14, 0.7)}})
    add({"id": "park-outline", "type": "line", "source": SRC, "source-layer": "park", "minzoom": 9, "paint": {
        "line-color": c["park_line"], "line-width": zoom(9, 0.4, 14, 1), "line-dasharray": [3, 2], "line-opacity": 0.8}})

    # Water
    add({"id": "water", "type": "fill", "source": SRC, "source-layer": "water", "paint": {"fill-color": c["water"]}})
    for wid, intermittent, dash in (("waterway", 0, None), ("waterway-intermittent", 1, [3, 2])):
        paint = {"line-color": c["water_line"],
                 "line-width": ["interpolate", ["exponential", 1.4], ["zoom"], 6, ["match", ["get", "class"], "river", 0.6, 0.2],
                                14, ["match", ["get", "class"], "river", 4, "canal", 2.4, 1.2]]}
        if dash:
            paint["line-dasharray"] = dash
        flt = ["all", ["!=", ["get", "brunnel"], "tunnel"],
               ["==", ["get", "intermittent"], 1] if intermittent else ["!=", ["get", "intermittent"], 1]]
        add({"id": wid, "type": "line", "source": SRC, "source-layer": "waterway", "minzoom": 6, "filter": flt,
             "layout": {"line-cap": "round"}, "paint": paint})

    # Aeroway
    add({"id": "aeroway-area", "type": "fill", "source": SRC, "source-layer": "aeroway", "minzoom": 10,
         "filter": ["==", ["geometry-type"], "Polygon"], "paint": {"fill-color": c["industrial"], "fill-opacity": 0.8}})
    add({"id": "aeroway-line", "type": "line", "source": SRC, "source-layer": "aeroway", "minzoom": 10,
         "filter": ["==", ["geometry-type"], "LineString"], "paint": {
        "line-color": c["casing_minor"],
        "line-width": ["interpolate", ["exponential", 1.4], ["zoom"], 10, ["match", ["get", "class"], "runway", 1.5, 0.5],
                       14, ["match", ["get", "class"], "runway", 14, 4]]}})

    # Buildings
    add({"id": "buildings", "type": "fill", "source": SRC, "source-layer": "building", "minzoom": 13, "paint": {
        "fill-color": c["building"], "fill-outline-color": c["building_line"], "fill-opacity": zoom(13, 0.0, 14, 0.85, 16, 1)}})

    # Roads: casing under fill, grouped by class. Tunnels are dashed/faded, bridges get a darker casing.
    not_tunnel = ["!=", ["get", "brunnel"], "tunnel"]
    classes = [
        # id, filter on class, colour keys, min zoom, width stops (z, w, z, w)
        ("service", ["service"], "minor", 14, (14, 0.8, 18, 6)),
        ("track", ["track"], "path_dash", 13, (13, 0.6, 18, 3)),
        ("minor", ["minor", "raceway", "busway"], "minor", 12, (12, 0.7, 14, 3, 18, 14)),
        ("tertiary", ["tertiary"], "minor", 10, (10, 0.6, 14, 4, 18, 18)),
        ("secondary", ["secondary"], "major", 8, (8, 0.6, 14, 5.5, 18, 22)),
        ("primary", ["primary"], "primary", 7, (7, 0.7, 14, 7, 18, 26)),
        ("trunk", ["trunk"], "primary", 6, (6, 0.7, 14, 8, 18, 28)),
        ("motorway", ["motorway"], "motorway", 6, (6, 0.7, 14, 9, 18, 30)),
    ]

    def road_filter(cls_list, extra=None):
        flt = ["all", ["in", ["get", "class"], ["literal", cls_list]]]
        if extra:
            flt.append(extra)
        return flt

    for rid, cls_list, tone, minz, widths in classes:
        if tone == "path_dash":
            continue
        casing_color = {"minor": c["casing_minor"], "major": c["casing_major"], "primary": c["casing_primary"], "motorway": c["casing_motorway"]}[tone]
        fill_color = {"minor": c["road_minor"], "major": c["road_major"], "primary": c["road_primary"], "motorway": c["road_motorway"]}[tone]
        w = zoom(*widths)
        wc = zoom(*(v if i % 2 == 0 else v * 1.3 + 0.8 for i, v in enumerate(widths)))  # casing = fill width + outline
        add({"id": f"road-{rid}-tunnel", "type": "line", "source": SRC, "source-layer": "transportation", "minzoom": minz,
             "filter": road_filter(cls_list, ["==", ["get", "brunnel"], "tunnel"]), "layout": {"line-cap": "butt", "line-join": "round"},
             "paint": {"line-color": fill_color, "line-width": w, "line-opacity": 0.55, "line-dasharray": [2, 1.5]}})
        add({"id": f"road-{rid}-casing", "type": "line", "source": SRC, "source-layer": "transportation", "minzoom": minz,
             "filter": road_filter(cls_list, not_tunnel), "layout": {"line-cap": "round", "line-join": "round"},
             "paint": {"line-color": casing_color, "line-width": wc}})
        add({"id": f"road-{rid}", "type": "line", "source": SRC, "source-layer": "transportation", "minzoom": minz,
             "filter": road_filter(cls_list, not_tunnel), "layout": {"line-cap": "round", "line-join": "round"},
             "paint": {"line-color": fill_color, "line-width": w}})
    add({"id": "road-track", "type": "line", "source": SRC, "source-layer": "transportation", "minzoom": 13,
         "filter": road_filter(["track"]), "paint": {"line-color": c["path"], "line-width": zoom(13, 0.5, 18, 2.5), "line-dasharray": [3, 2]}})
    add({"id": "road-path", "type": "line", "source": SRC, "source-layer": "transportation", "minzoom": 14,
         "filter": road_filter(["path"]), "paint": {"line-color": c["path"], "line-width": zoom(14, 0.6, 18, 2), "line-dasharray": [1, 1.6]}})
    add({"id": "rail", "type": "line", "source": SRC, "source-layer": "transportation", "minzoom": 9,
         "filter": road_filter(["rail", "transit"], not_tunnel), "paint": {
        "line-color": c["rail"], "line-width": zoom(9, 0.5, 16, 2), "line-dasharray": [4, 3]}})

    # Administrative boundaries (country solid, region dotted); maritime lines omitted.
    add({"id": "boundary-state", "type": "line", "source": SRC, "source-layer": "boundary", "minzoom": 4,
         "filter": ["all", ["==", ["get", "admin_level"], 4], ["!=", ["get", "maritime"], 1]],
         "paint": {"line-color": c["boundary_state"], "line-width": zoom(4, 0.6, 10, 1.4), "line-dasharray": [2, 2]}})
    add({"id": "boundary-country", "type": "line", "source": SRC, "source-layer": "boundary", "minzoom": 0,
         "filter": ["all", ["==", ["get", "admin_level"], 2], ["!=", ["get", "maritime"], 1]],
         "paint": {"line-color": c["boundary"], "line-width": zoom(0, 0.6, 8, 1.6, 14, 2.4)}})

    # ---- Labels --------------------------------------------------------------------------------------------------
    label_halo = {"text-halo-color": c["halo"], "text-halo-width": 1.6, "text-halo-blur": 0.4}
    add({"id": "water-labels", "type": "symbol", "source": SRC, "source-layer": "water_name", "minzoom": 5, "layout": {
        "text-font": F_ITAL, "text-size": zoom(5, 10, 14, 14), "text-max-width": 7,
        "text-letter-spacing": 0.1}, "paint": {"text-color": c["text_water"], **label_halo}}, text=name_field)
    add({"id": "waterway-labels", "type": "symbol", "source": SRC, "source-layer": "waterway", "minzoom": 11,
         "filter": ["has", "name"], "layout": {"text-font": F_ITAL, "symbol-placement": "line",
                                                "text-size": 11, "text-max-angle": 30}, "paint": {"text-color": c["text_water"], **label_halo}}, text=name_field)
    add({"id": "street-labels", "type": "symbol", "source": SRC, "source-layer": "transportation_name", "minzoom": 12,
         "filter": ["has", "name"], "layout": {
        "text-font": F_REG, "symbol-placement": "line", "text-size": zoom(12, 10, 17, 14),
        "text-rotation-alignment": "map", "text-max-angle": 35, "symbol-spacing": 280, "text-padding": 2},
        "paint": {"text-color": c["text_road"], "text-halo-color": c["halo"], "text-halo-width": 1.8}}, text=name_field)
    add({"id": "road-refs", "type": "symbol", "source": SRC, "source-layer": "transportation_name", "minzoom": 8,
         "filter": ["all", ["has", "ref"], ["in", ["get", "class"], ["literal", ["motorway", "trunk", "primary"]]]], "layout": {
        "text-field": ["get", "ref"], "text-font": F_SEMI, "symbol-placement": "line", "text-size": 10, "symbol-spacing": 400, "text-rotation-alignment": "viewport"},
        "paint": {"text-color": c["text_muted"], "text-halo-color": c["halo"], "text-halo-width": 1.6}})
    add({"id": "housenumbers", "type": "symbol", "source": SRC, "source-layer": "housenumber", "minzoom": 16, "layout": {
        "text-field": ["get", "housenumber"], "text-font": F_REG, "text-size": 10, "text-padding": 2},
        "paint": {"text-color": c["text_muted"], "text-halo-color": c["halo"], "text-halo-width": 1.2}})

    # POIs: coloured dots by category (no sprite sheet is hosted); names from z16.
    poi_groups = [
        (c["poi_food"], ["restaurant", "cafe", "fast_food", "bar", "bakery", "ice_cream", "pub", "food_court"]),
        (c["poi_shop"], ["shop", "supermarket", "convenience", "clothing_store", "mall", "department_store", "grocery", "market", "marketplace", "butcher", "florist", "furniture", "electronics", "hardware", "jewelry", "mobile_phone", "bicycle", "alcohol_shop", "beauty"]),
        (c["poi_health"], ["hospital", "pharmacy", "doctor", "dentist", "clinic", "veterinary", "optician"]),
        (c["poi_edu"], ["school", "kindergarten", "college", "university", "library"]),
        (c["poi_transport"], ["bus", "railway", "subway", "aerialway", "taxi", "ferry_terminal", "bicycle_rental", "car_rental"]),
        (c["poi_lodging"], ["lodging", "hotel", "hostel", "guest_house", "motel", "camp_site"]),
        (c["poi_finance"], ["bank", "atm", "post", "post_box", "police", "fire_station", "town_hall", "courthouse"]),
        (c["poi_fuel"], ["fuel", "charging_station", "car_repair", "car", "parking"]),
    ]
    poi_color = ["match", ["get", "class"]]
    for color, classes_ in poi_groups:
        poi_color += [classes_, color]
    poi_color.append(c["poi_default"])
    known = [cls for _, group in poi_groups for cls in group]
    dot = {"circle-color": poi_color, "circle-radius": zoom(15, 2.5, 18, 5), "circle-stroke-color": c["poi_stroke"], "circle-stroke-width": 1}
    add({"id": "poi-dots", "type": "circle", "source": SRC, "source-layer": "poi", "minzoom": 15.5,
         "filter": ["in", ["get", "class"], ["literal", known]], "paint": dot})
    add({"id": "poi-dots-other", "type": "circle", "source": SRC, "source-layer": "poi", "minzoom": 17,
         "filter": ["!", ["in", ["get", "class"], ["literal", known]]], "paint": {**dot, "circle-radius": zoom(17, 2, 18, 3.5), "circle-opacity": 0.8}})
    add({"id": "poi-labels", "type": "symbol", "source": SRC, "source-layer": "poi", "minzoom": 15.5,
         "filter": ["has", "name"], "layout": {"text-font": F_REG, "text-size": 11, "text-offset": [0, 0.9],
                                                "text-anchor": "top", "text-max-width": 8, "text-optional": True, "text-padding": 3,
                                                "symbol-sort-key": ["get", "rank"]},
         "paint": {"text-color": c["text"], **label_halo}}, text=name_field)
    add({"id": "peak-labels", "type": "symbol", "source": SRC, "source-layer": "mountain_peak", "minzoom": 9,
         "filter": ["has", "name"], "layout": {"text-font": F_REG, "text-size": 10, "text-offset": [0, 0.6], "text-anchor": "top", "text-max-width": 8,
                                                "symbol-sort-key": ["-", ["to-number", ["get", "ele"], 0]]},
         "paint": {"text-color": c["peak"], **label_halo}},
        text=lambda lang: ["concat", name_field(lang), ["case", ["has", "ele"], ["concat", "\n", ["to-string", ["get", "ele"]], " m"], ""]])
    add({"id": "aerodrome-labels", "type": "symbol", "source": SRC, "source-layer": "aerodrome_label", "minzoom": 9,
         "filter": ["has", "name"], "layout": {"text-font": F_SEMI, "text-size": 11, "text-max-width": 7, "text-anchor": "top", "text-offset": [0, 0.4]},
         "paint": {"text-color": c["poi_transport"], **label_halo}}, text=name_field)

    def place(id_, cls_list, minz, maxz, sizes, font, color_key="text", upper=False, extra_filter=None):
        flt = ["all", ["in", ["get", "class"], ["literal", cls_list]]]
        if extra_filter:
            flt.append(extra_filter)
        layout = {"text-font": font, "text-size": zoom(*sizes), "text-max-width": 8,
                  "symbol-sort-key": ["get", "rank"], "text-padding": 3}
        if upper:
            layout["text-transform"] = "uppercase"
            layout["text-letter-spacing"] = 0.08
        layer = {"id": id_, "type": "symbol", "source": SRC, "source-layer": "place", "minzoom": minz, "filter": flt, "layout": layout,
                 "paint": {"text-color": c[color_key], "text-halo-color": c["halo"], "text-halo-width": 2, "text-halo-blur": 0.5}}
        if maxz is not None:
            layer["maxzoom"] = maxz
        add(layer, text=name_field)

    place("place-country", ["country"], 1, 7, (1, 11, 6, 17), F_BOLD, "text_muted", upper=True)
    place("place-state", ["state", "province"], 4, 9, (4, 10, 8, 14), F_SEMI, "text_muted", upper=True)
    place("place-labels", ["city"], 3, None, (3, 11, 8, 15, 12, 21), F_SEMI)   # id kept: the web app queries it on map click
    place("place-town", ["town"], 7, None, (7, 11, 12, 16), F_SEMI)
    place("place-village", ["village"], 9, None, (9, 10, 14, 14), F_REG)
    place("place-hamlet", ["hamlet", "isolated_dwelling"], 11, None, (11, 10, 15, 13), F_REG, "text_muted")
    place("place-suburb", ["suburb", "quarter", "neighbourhood"], 11, None, (11, 10, 16, 14), F_REG, "text_muted", upper=True)

    return {
        "version": 8,
        "name": f"KUNDE Maps - {theme}",
        "metadata": {"kunde:style-version": 2, "kunde:theme": theme, "kunde:generator": "scripts/build-style.py"},
        "center": [76.945, 43.238],
        "zoom": 11,
        "sources": {SRC: {
            "type": "vector", "url": "pmtiles://http://localhost:8080/tiles/kazakhstan.pmtiles",
            "attribution": "© <a href=\"https://www.openstreetmap.org/copyright\">OpenStreetMap contributors</a> © <a href=\"https://openmaptiles.org/\">OpenMapTiles</a>"}},
        "glyphs": GLYPHS,
        "layers": layers,
    }


def render(theme, native=False):
    style = build(theme)
    if native:
        # The SDK injects the configured HTTPS tile origin before rendering.
        del style["sources"][SRC]["url"]
    return json.dumps(style, ensure_ascii=False, indent=1) + "\n"


def main():
    targets = {
        ROOT / folder / filename: (theme, native)
        for folder, native in (("apps/web", False), ("packages/kunde_maps_sdk/assets", True))
        for filename, theme in (("style.json", "light"), ("style-dark.json", "dark"))
    }
    if "--check" in sys.argv:
        stale = [str(p) for p, args in targets.items() if not p.exists() or p.read_text(encoding="utf-8") != render(*args)]
        if stale:
            print("Out of date (run scripts/build-style.py):", *stale, sep="\n  ")
            return 1
        print("Styles are up to date")
        return 0
    for path, (theme, native) in targets.items():
        path.write_text(render(theme, native), encoding="utf-8")
        print("wrote", path.relative_to(ROOT), f"({len(build(theme)['layers'])} layers)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
